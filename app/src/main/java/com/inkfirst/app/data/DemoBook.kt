package com.inkfirst.app.data

import android.content.Context
import android.util.Log
import java.io.File

/**
 * The book a new reader meets before they have an API key.
 *
 * Without it the first thing the app asks for is a Gemini key, which means a
 * Play reviewer never sees a page and a tester has an errand before they have
 * a reason. So one real book ships inside the APK: the outline, and chapters
 * one and two already written. Chapters three onward are `pending`, which is
 * the app's own ordinary state — compiling chapter three is what asks for a
 * key, at the moment someone has read enough to want it.
 *
 * It is a REAL book rather than a sample: generated by the app, illustrated by
 * the app, with the course memory chapter three will be written against. The
 * reader's own ink, annotations and reading positions were stripped before it
 * was bundled; what remains is the book, not anyone's copy of it.
 */
object DemoBook {

    /** Mirrors the asset path `assets/demo/<slug>`. */
    const val SLUG = "pen-and-paper-confidence-drawing-real-life-without-looking-f"

    /**
     * The marker lives in the COURSES ROOT, not in app storage, and that is
     * the whole design. Deleting the demo has to stay deleted — including
     * across a reinstall, which is exactly when a preference would forget and
     * put the book back in front of someone who already threw it away. The
     * courses root outlives the install; the decision belongs with it.
     */
    private const val MARKER = ".demo-installed"

    /**
     * Copies the demo into [root] the first time, and never again.
     *
     * Returns true only when something was written, so the caller knows
     * whether the shelf it is about to read has changed.
     */
    fun installIfAbsent(context: Context, root: File): Boolean {
        val marker = File(root, MARKER)
        if (marker.exists()) return false
        // Already there — a restored backup, or a copy made by hand. Record
        // the decision anyway so this never runs again.
        if (File(root, SLUG).exists()) {
            writeMarker(marker, "already present")
            return false
        }
        return try {
            root.mkdirs()
            copyAsset(context, "demo/$SLUG", File(root, SLUG))
            writeMarker(marker, "installed")
            true
        } catch (e: Exception) {
            // A shelf with no demo is a working app; a crash on first launch
            // is not. Leave no marker, so a later launch can try again.
            Log.w("Zhuzha", "demo book not installed: ${e.message}")
            File(root, SLUG).deleteRecursively()
            false
        }
    }

    private fun writeMarker(marker: File, what: String) {
        marker.writeText(
            "Zhuzha wrote the demo book here once ($what).\n" +
                "This file stops it coming back if you delete the book.\n" +
                "Remove this file to have it offered again.\n",
        )
    }

    /**
     * AssetManager has no isDirectory, and `list()` on a file returns empty —
     * so emptiness is how a leaf is recognised. That misreads an EMPTY
     * directory as a file; the demo has none, and an empty directory would
     * carry nothing anyway.
     */
    private fun copyAsset(context: Context, assetPath: String, target: File) {
        val children = context.assets.list(assetPath).orEmpty()
        if (children.isEmpty()) {
            target.parentFile?.mkdirs()
            context.assets.open(assetPath).use { input ->
                target.outputStream().use { input.copyTo(it) }
            }
            return
        }
        target.mkdirs()
        for (child in children) {
            copyAsset(context, "$assetPath/$child", File(target, child))
        }
    }
}
